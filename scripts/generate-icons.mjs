import fs from 'node:fs';
import path from 'node:path';

const packageRoot = path.resolve('node_modules/@material-design-icons/svg');
const version = JSON.parse(fs.readFileSync(path.join(packageRoot, 'package.json'), 'utf8')).version;

const icons = [
  ['favorite', 'outlined/favorite.svg'],
  ['favoriteBorder', 'outlined/favorite_border.svg'],
  ['edit', 'outlined/edit.svg'],
  ['delete', 'outlined/delete.svg'],
  ['chatBubbleOutline', 'outlined/chat_bubble_outline.svg'],
  ['home', 'outlined/home.svg'],
  ['groups', 'outlined/groups.svg'],
  ['search', 'outlined/search.svg'],
  ['notifications', 'outlined/notifications.svg'],
  ['person', 'outlined/person.svg'],
  ['settings', 'outlined/settings.svg'],
  ['logout', 'outlined/logout.svg'],
  ['login', 'outlined/login.svg'],
  ['language', 'outlined/language.svg'],
  ['menu', 'outlined/menu.svg'],
  ['close', 'outlined/close.svg'],
];

const entries = icons.map(([name, file]) => {
  const source = fs.readFileSync(path.join(packageRoot, file), 'utf8');
  const paths = [...source.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)];
  if (paths.length !== 1) {
    throw new Error(`${file}: expected exactly one path, found ${paths.length}`);
  }
  return [name, paths[0][1]];
});

const defs = entries
  .map(([name, d]) => `${name} : String\n${name} =\n    ${JSON.stringify(d)}\n`)
  .join('\n\n');

const exposing = entries.map(([name]) => name).sort().join(', ');

const output = `module Generated.Icons exposing (${exposing})

{-| Generated by scripts/generate-icons.mjs from @material-design-icons/svg ${version}.

Material Design Icons are licensed under the Apache License 2.0.
Do not edit this file by hand; run \`npm run icons:generate\` instead.

-}


${defs}`;

fs.writeFileSync('src/Generated/Icons.elm', output);
